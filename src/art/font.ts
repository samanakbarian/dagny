export interface Glyph {
  w: number;
  top: number;
  rows: string[];
}

export function parseGlyph(src: string): Glyph {
  const colon = src.indexOf(':');
  const top = Number(src.slice(0, colon));
  const rows = src.slice(colon + 1).split('/');
  return { w: rows[0].length, top, rows };
}

/** Characters the font can draw. */
export function hasGlyph(ch: string): boolean {
  return ch in GLYPHS;
}
